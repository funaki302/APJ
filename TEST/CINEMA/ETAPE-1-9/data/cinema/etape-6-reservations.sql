-- =====================================================================
-- CINEMA - Etape 6 : reservations (tickets)
-- Tables : CIN_TICKET (mere), CIN_TICKET_DETAIL (une ligne par place)
-- Vues : CIN_TICKET_LIB, CIN_TICKET_DETAIL_LIB, CIN_PLACE_DIFFUSION (etat de chaque place pour chaque seance)
-- Menus Cinema > Reservations.
-- Prerequis : etape-5-diffusions.sql. Se reconnecter apres execution (menu en session).
--
-- ETAT ticket : 1 = reserve, 11 = paye (etape 7), 0 = annule.
-- Un ticket reserve (etat 1) EXPIRE quand on arrive a DELAI_EXPIRATION_MIN minutes (CIN_PARAMETRE, 30 par defaut)
-- avant le debut de la seance : il n'est plus payable et ses places redeviennent libres. Calcul dans les vues,
-- aucune tache planifiee. Un ticket "actif" (qui occupe ses places) = paye, ou reserve et pas encore expire.
-- =====================================================================

SET DEFINE OFF;

CREATE TABLE CIN_TICKET (
    ID                VARCHAR2(50)  NOT NULL,
    IDCLIENT          VARCHAR2(255) NOT NULL,
    IDDIFFUSION       VARCHAR2(50)  NOT NULL,
    DATY_RESERVATION  DATE          NOT NULL,
    HEURE_RESERVATION VARCHAR2(8),
    MONTANT           NUMBER(15, 2) DEFAULT 0 NOT NULL,
    REMARQUE          VARCHAR2(500),
    ETAT              NUMBER(2) DEFAULT 1,
    CONSTRAINT PK_CIN_TICKET PRIMARY KEY (ID),
    CONSTRAINT FK_CIN_TICKET_CLIENT FOREIGN KEY (IDCLIENT) REFERENCES CLIENT (ID),
    CONSTRAINT FK_CIN_TICKET_DIFFUSION FOREIGN KEY (IDDIFFUSION) REFERENCES CIN_DIFFUSION (ID),
    CONSTRAINT CK_CIN_TICKET_MONTANT CHECK (MONTANT >= 0),
    CONSTRAINT CK_CIN_TICKET_ETAT CHECK (ETAT IN (0, 1, 11))
);

CREATE INDEX IX_CIN_TICKET_DIFFUSION ON CIN_TICKET (IDDIFFUSION);
CREATE INDEX IX_CIN_TICKET_CLIENT ON CIN_TICKET (IDCLIENT);

-- IDDIFFUSION recopie de la mere : permet de controler qu'une place n'est prise qu'une fois par seance
CREATE TABLE CIN_TICKET_DETAIL (
    ID          VARCHAR2(50)  NOT NULL,
    IDTICKET    VARCHAR2(50)  NOT NULL,
    IDDIFFUSION VARCHAR2(50)  NOT NULL,
    IDPLACE     VARCHAR2(50)  NOT NULL,
    IDCLASSE    VARCHAR2(50)  NOT NULL,
    PRIX        NUMBER(15, 2) NOT NULL,
    ETAT        NUMBER(2) DEFAULT 1,
    CONSTRAINT PK_CIN_TICKET_DETAIL PRIMARY KEY (ID),
    CONSTRAINT FK_CIN_TICKET_DETAIL_TICKET FOREIGN KEY (IDTICKET) REFERENCES CIN_TICKET (ID) ON DELETE CASCADE,
    CONSTRAINT FK_CIN_TICKET_DETAIL_DIFF FOREIGN KEY (IDDIFFUSION) REFERENCES CIN_DIFFUSION (ID),
    CONSTRAINT FK_CIN_TICKET_DETAIL_PLACE FOREIGN KEY (IDPLACE) REFERENCES CIN_PLACE (ID),
    CONSTRAINT FK_CIN_TICKET_DETAIL_CLASSE FOREIGN KEY (IDCLASSE) REFERENCES CIN_CLASSE_PLACE (ID),
    CONSTRAINT UK_CIN_TICKET_DETAIL_PLACE UNIQUE (IDTICKET, IDPLACE),
    CONSTRAINT CK_CIN_TICKET_DETAIL_PRIX CHECK (PRIX >= 0)
);

CREATE INDEX IX_CIN_TICKET_DETAIL_DIFF ON CIN_TICKET_DETAIL (IDDIFFUSION, IDPLACE);

CREATE SEQUENCE SEQ_CIN_TICKET START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CIN_TICKET_DETAIL START WITH 1 INCREMENT BY 1 CACHE 20;

CREATE OR REPLACE FUNCTION GETSEQCINTICKET RETURN NUMBER IS
    retour NUMBER;
BEGIN
    SELECT SEQ_CIN_TICKET.NEXTVAL INTO retour FROM DUAL;
    RETURN retour;
END;
/

CREATE OR REPLACE FUNCTION GETSEQCINTICKETDETAIL RETURN NUMBER IS
    retour NUMBER;
BEGIN
    SELECT SEQ_CIN_TICKET_DETAIL.NEXTVAL INTO retour FROM DUAL;
    RETURN retour;
END;
/

-- Ticket avec client, seance, date limite de paiement et statut calcule (Reserve / Paye / Expire / Annule)
CREATE OR REPLACE VIEW CIN_TICKET_LIB AS
SELECT x.*,
       CASE WHEN x.ETAT = 0 THEN 'Annul&eacute;'
            WHEN x.ETAT = 11 THEN 'Pay&eacute;'
            WHEN SYSDATE > x.DATE_LIMITE THEN 'Expir&eacute;'
            ELSE 'R&eacute;serv&eacute;' END AS ETATLIB,
       CASE WHEN x.ETAT = 11 OR (x.ETAT = 1 AND SYSDATE <= x.DATE_LIMITE) THEN 1 ELSE 0 END AS ACTIF,
       TO_CHAR(x.DATE_LIMITE, 'DD/MM/YYYY HH24:MI') AS DATE_LIMITELIB
FROM (
    SELECT t.ID, t.IDCLIENT, cl.NOM AS IDCLIENTLIB, cl.TELEPHONE, t.IDDIFFUSION,
           d.IDFILM, d.IDFILMLIB, d.IDSALLE, d.IDSALLELIB, d.DATY AS DATY_DIFFUSION, d.HEURE, d.HEURE_FIN,
           d.DATE_DEBUT, d.ETAT AS ETAT_DIFFUSION,
           d.DATE_DEBUT - NVL((SELECT TO_NUMBER(p.VALEUR) FROM CIN_PARAMETRE p WHERE p.CODE = 'DELAI_EXPIRATION_MIN'), 30) / 1440 AS DATE_LIMITE,
           t.DATY_RESERVATION, t.HEURE_RESERVATION, t.MONTANT, t.REMARQUE, t.ETAT,
           (SELECT COUNT(*) FROM CIN_TICKET_DETAIL td WHERE td.IDTICKET = t.ID) AS NB_PLACES
    FROM CIN_TICKET t
    JOIN CLIENT cl ON cl.ID = t.IDCLIENT
    JOIN CIN_DIFFUSION_LIB d ON d.ID = t.IDDIFFUSION
) x;

-- Places d'un ticket avec numero et classe
CREATE OR REPLACE VIEW CIN_TICKET_DETAIL_LIB AS
SELECT td.ID, td.IDTICKET, td.IDDIFFUSION, td.IDPLACE, p.NUMERO, p.RANGEE, p.COLONNE,
       td.IDCLASSE, cl.VAL AS IDCLASSELIB, cl.COULEUR, td.PRIX, td.ETAT
FROM CIN_TICKET_DETAIL td
JOIN CIN_PLACE p ON p.ID = td.IDPLACE
JOIN CIN_CLASSE_PLACE cl ON cl.ID = td.IDCLASSE;

-- Etat de chaque place de la salle pour chaque seance :
-- HS (hors service), PAYEE, RESERVEE (ticket reserve non expire) ou LIBRE
CREATE OR REPLACE VIEW CIN_PLACE_DIFFUSION AS
SELECT d.ID AS IDDIFFUSION, p.ID AS IDPLACE, p.NUMERO, p.RANGEE, p.COLONNE, p.IDCLASSE, p.IDCLASSELIB, p.COULEUR, p.PRIX,
       occ.IDTICKET,
       CASE WHEN p.ETAT = 0 THEN 'HS'
            WHEN occ.ETAT = 11 THEN 'PAYEE'
            WHEN occ.ETAT = 1 THEN 'RESERVEE'
            ELSE 'LIBRE' END AS STATUT
FROM CIN_DIFFUSION d
JOIN CIN_PLACE_LIB p ON p.IDSALLE = d.IDSALLE
LEFT JOIN (
    SELECT td.IDDIFFUSION, td.IDPLACE, MAX(t.ID) AS IDTICKET, MAX(t.ETAT) AS ETAT
    FROM CIN_TICKET_DETAIL td
    JOIN CIN_TICKET_LIB t ON t.ID = td.IDTICKET
    WHERE t.ACTIF = 1
    GROUP BY td.IDDIFFUSION, td.IDPLACE
) occ ON occ.IDDIFFUSION = d.ID AND occ.IDPLACE = p.ID;

