--- Corriger vue  SUIVIJOURNALIER_LIB
CREATE OR REPLACE VIEW SUIVIJOURNALIER_LIB AS
SELECT s.ID, s.DATY, 
       l.IDFERME AS IDFERME, 
       s.IDLOT,
       m.VAL    AS IDFERMELIB,
       l.NOMLOT AS IDLOTLIB,
       so.VAL   AS IDSOUCHELIB,
       s.ETAT   AS IDETAT,
       CASE s.ETAT
           WHEN 1  THEN 'CREE'
           WHEN 11 THEN 'VALIDE'
           WHEN 0  THEN 'ANULLE'
       END AS ETATLIB
FROM SUIVIJOURNALIER s
         LEFT JOIN LOT l      ON l.ID = s.IDLOT
         LEFT JOIN MAGASIN2 m ON m.ID = l.IDFERME
         LEFT JOIN SOUCHE so  ON so.ID = l.IDSOUCHE;