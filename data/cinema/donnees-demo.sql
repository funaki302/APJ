    ticket('CINTKTDEMO05', 'CLICINDEMO01', 'CINDIFDEMO02', '2', 'A01,A02', 1, 0);       -- seance dans 20 min : expire
    ticket('CINTKTDEMO06', 'CLICINDEMO02', 'CINDIFDEMO04', '1', 'E01,E02', 11, 1);      -- demain 20:30 : 2 Moyen, paye
