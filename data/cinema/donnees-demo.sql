DECLARE
    PROCEDURE ticket(p_id VARCHAR2, p_client VARCHAR2, p_diffusion VARCHAR2, p_salle_code VARCHAR2, p_places VARCHAR2, p_etat NUMBER, p_jours_avant NUMBER) IS
        v_montant NUMBER := 0;
        v_num     NUMBER := 0;
    BEGIN
        INSERT INTO CIN_TICKET (ID, IDCLIENT, IDDIFFUSION, DATY_RESERVATION, HEURE_RESERVATION, MONTANT, ETAT)
        VALUES (p_id, p_client, p_diffusion, TRUNC(SYSDATE) - p_jours_avant, '10:15:00', 0, p_etat);
        FOR pl IN (SELECT p.ID, p.IDCLASSE, c.PRIX FROM CIN_PLACE p JOIN CIN_CLASSE_PLACE c ON c.ID = p.IDCLASSE
                   WHERE p.ID IN (SELECT 'CINPLADEMO' || p_salle_code || REGEXP_SUBSTR(p_places, '[^,]+', 1, LEVEL) FROM DUAL
                                  CONNECT BY REGEXP_SUBSTR(p_places, '[^,]+', 1, LEVEL) IS NOT NULL)) LOOP
            v_num := v_num + 1;
            INSERT INTO CIN_TICKET_DETAIL (ID, IDTICKET, IDDIFFUSION, IDPLACE, IDCLASSE, PRIX, ETAT)
            VALUES (p_id || '-' || v_num, p_id, p_diffusion, pl.ID, pl.IDCLASSE, pl.PRIX, p_etat);
            v_montant := v_montant + pl.PRIX;
        END LOOP;
        UPDATE CIN_TICKET SET MONTANT = v_montant WHERE ID = p_id;
    END;
BEGIN
    ticket('CINTKTDEMO01', 'CLICINDEMO01', 'CINDIFDEMO03', '1', 'C05,C06', 1, 1);       -- demain 18:00 : 2 Standard
    ticket('CINTKTDEMO02', 'CLICINDEMO02', 'CINDIFDEMO03', '1', 'F04,F05,F06', 1, 0);   -- demain 18:00 : 3 Premium
