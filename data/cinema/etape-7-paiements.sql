CREATE OR REPLACE VIEW CIN_MODE_CAISSE_LIB AS
SELECT mc.ID, mc.IDMODEPAIEMENT, m.VAL AS IDMODEPAIEMENTLIB, mc.IDCAISSE, c.VAL AS IDCAISSELIB, mc.ACTIF,
       DECODE(mc.ACTIF, 1, 'Oui', 'Non') AS ACTIFLIB
FROM CIN_MODE_CAISSE mc
JOIN MODEPAIEMENT m ON m.ID = mc.IDMODEPAIEMENT
JOIN CAISSE c ON c.ID = mc.IDCAISSE;

-- Paiement avec client, seance, facture et liste des modes utilises
CREATE OR REPLACE VIEW CIN_PAIEMENT_LIB AS
SELECT p.ID, p.IDTICKET, p.IDCLIENT, cl.NOM AS IDCLIENTLIB, t.IDDIFFUSION, d.IDFILMLIB, d.IDSALLELIB,
       d.DATY AS DATY_DIFFUSION, d.HEURE, p.DATY, p.HEURE AS HEURE_PAIEMENT, p.MONTANT, p.IDFACTURE, f.NUMERO AS NUMERO_FACTURE,
       (SELECT LISTAGG(m.VAL || ' ' || TO_CHAR(pd.MONTANT, 'FM999G999G999G990', 'NLS_NUMERIC_CHARACTERS='', ''') , ' + ') WITHIN GROUP (ORDER BY pd.ID)
        FROM CIN_PAIEMENT_DETAIL pd JOIN MODEPAIEMENT m ON m.ID = pd.IDMODEPAIEMENT WHERE pd.IDPAIEMENT = p.ID) AS MODES,
       p.ETAT
FROM CIN_PAIEMENT p
JOIN CLIENT cl ON cl.ID = p.IDCLIENT
JOIN CIN_TICKET t ON t.ID = p.IDTICKET
JOIN CIN_DIFFUSION_LIB d ON d.ID = t.IDDIFFUSION
LEFT JOIN CIN_FACTURE f ON f.ID = p.IDFACTURE;

CREATE OR REPLACE VIEW CIN_PAIEMENT_DETAIL_LIB AS
SELECT pd.ID, pd.IDPAIEMENT, pd.IDMODEPAIEMENT, m.VAL AS IDMODEPAIEMENTLIB, pd.IDCAISSE, c.VAL AS IDCAISSELIB,
       pd.MONTANT, pd.IDMVTCAISSE, pd.ETAT
FROM CIN_PAIEMENT_DETAIL pd
JOIN MODEPAIEMENT m ON m.ID = pd.IDMODEPAIEMENT
JOIN CAISSE c ON c.ID = pd.IDCAISSE;

-- Facture avec client et seance
CREATE OR REPLACE VIEW CIN_FACTURE_LIB AS
SELECT f.ID, f.NUMERO, f.IDCLIENT, cl.NOM AS IDCLIENTLIB, cl.TELEPHONE, f.IDTICKET, f.IDPAIEMENT, t.IDDIFFUSION,
       d.IDFILMLIB, d.IDSALLELIB, d.DATY AS DATY_DIFFUSION, d.HEURE, f.DATY, f.MONTANT,
       (SELECT COUNT(*) FROM CIN_FACTURE_DETAIL fd WHERE fd.IDFACTURE = f.ID) AS NB_PLACES, f.ETAT
FROM CIN_FACTURE f
JOIN CLIENT cl ON cl.ID = f.IDCLIENT
JOIN CIN_TICKET t ON t.ID = f.IDTICKET
JOIN CIN_DIFFUSION_LIB d ON d.ID = t.IDDIFFUSION;

