CREATE TABLE CIN_PAIEMENT (
    ID        VARCHAR2(50)  NOT NULL,
    IDTICKET  VARCHAR2(50)  NOT NULL,
    IDCLIENT  VARCHAR2(255) NOT NULL,
    DATY      DATE          NOT NULL,
    HEURE     VARCHAR2(8),
    MONTANT   NUMBER(15, 2) NOT NULL,
    IDFACTURE VARCHAR2(50),
    ETAT      NUMBER(2) DEFAULT 11,
    CONSTRAINT PK_CIN_PAIEMENT PRIMARY KEY (ID),
    CONSTRAINT UK_CIN_PAIEMENT_TICKET UNIQUE (IDTICKET),
    CONSTRAINT FK_CIN_PAIEMENT_TICKET FOREIGN KEY (IDTICKET) REFERENCES CIN_TICKET (ID),
    CONSTRAINT FK_CIN_PAIEMENT_CLIENT FOREIGN KEY (IDCLIENT) REFERENCES CLIENT (ID),
    CONSTRAINT CK_CIN_PAIEMENT_MONTANT CHECK (MONTANT > 0)
);

CREATE TABLE CIN_PAIEMENT_DETAIL (
    ID             VARCHAR2(50)  NOT NULL,
    IDPAIEMENT     VARCHAR2(50)  NOT NULL,
    IDMODEPAIEMENT VARCHAR2(255) NOT NULL,
    IDCAISSE       VARCHAR2(255) NOT NULL,
    MONTANT        NUMBER(15, 2) NOT NULL,
    IDMVTCAISSE    VARCHAR2(255),
    ETAT           NUMBER(2) DEFAULT 11,
    CONSTRAINT PK_CIN_PAIEMENT_DETAIL PRIMARY KEY (ID),
    CONSTRAINT FK_CIN_PAIEMENT_DETAIL_PAIE FOREIGN KEY (IDPAIEMENT) REFERENCES CIN_PAIEMENT (ID) ON DELETE CASCADE,
    CONSTRAINT FK_CIN_PAIEMENT_DETAIL_CAISSE FOREIGN KEY (IDCAISSE) REFERENCES CAISSE (ID),
    CONSTRAINT CK_CIN_PAIEMENT_DETAIL_MONTANT CHECK (MONTANT > 0)
);

CREATE INDEX IX_CIN_PAIEMENT_DETAIL_PAIE ON CIN_PAIEMENT_DETAIL (IDPAIEMENT);

